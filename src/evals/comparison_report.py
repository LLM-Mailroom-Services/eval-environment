"""Modal-comparable run reports for API (Leg B) comparison runs.

Mirrors the sandbox's Modal/vLLM run reports (e.g.
``local-mailroom-sandbox/reports/RUN-20-CORRESPONDENCE-AWQ-REPORT.md``) so a
Modal leg and an API leg of the same wave can be read side by side:

    Modal: RUN-20-CORRESPONDENCE-AWQ-REPORT.md        (engine = AWQ quant)
    API:   RUN-20-CORRESPONDENCE-QWEN3-8B-REPORT.md   (engine = model slug)

Naming schema
-------------
``reports/api-comparisons/<model_short>/<task>/RUN-<wave>-<CLASS>-<MODEL_SHORT>-REPORT.md``

- ``model_short``  top-level directory filed by the tested model (decode-profile
  key when set, else a slugified model id: ``qwen/qwen3-8b`` -> ``qwen-qwen3-8b``).
- ``task``         second-level directory: the eval task id (``contracts``,
  ``insurance_claims``, ``correspondence``, ``corporate_records``,
  ``merger_agreement``, ``classification``, …) — reports are always
  separated by specialist/task, never dumped flat across a model directory.
- ``wave``         draw size: ``params.sample`` when set, else ``params.n``.
- ``CLASS``        subset class uppercased (``class:correspondence`` ->
  ``CORRESPONDENCE``; whole-dataset runs -> ``ALL``).

The same wave+class stem appears in both legs' filenames, so pairing the
Modal and API reports is a filename join; the model variant is always the
last token.

Comparable metric surface (each Modal metric has an explicit analog here;
engine-only metrics like cold boot/gpu_seconds are stated as N/A rather than
omitted, so the two tables share a row vocabulary):

  Modal metric                      API analog in this report
  --------------------------------  --------------------------------------
  wall (busy interval)              wall (run duration_s)
  concurrency                       params.concurrency
  cold boot                         N/A (serverless API; no cold boot)
  gpu_seconds                       N/A (no local GPU)
  estimated GPU cost                cost_usd_est (token-priced, roster rates)
  cost per document                 cost_usd_est / docs scored
  latency e2e / p50 / max           same (case-row latency_ms, + p95)
  prompt/completion/total tokens    same (case-row tokens)
  cost cap                          profile cost_cap_usd -> under/over
  docs ok / total, overall score    same (metrics + case rows)
  per-document table                same columns incl. f1 + tokens
  engine / quant / vLLM config      provider + decode-posture table
  dataset draw (rev, seed, draw)    same provenance + manifest paths

Reports are generated by ``run_task`` whenever a ``decode_profile`` is active
(written before the experiment-log record so the path lands in the summary);
failures never fail the run (same law as tracing).
"""

from __future__ import annotations

import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from evals import run_report_analytics as rra

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_REPORTS_DIR = REPO_ROOT / "reports" / "api-comparisons"


def reports_dir() -> Path:
    """Report root — ``EVALS_COMPARISON_REPORTS_DIR`` override (tests redirect)."""
    override = os.environ.get("EVALS_COMPARISON_REPORTS_DIR")
    return Path(override) if override else DEFAULT_REPORTS_DIR

# Per-doc score keys, in display-priority order (first present wins per slot).
OVERALL_KEYS = ("overall_score", "overall_extraction_score", "accuracy", "exact_match", "score")
F1_KEYS = ("extraction_f1", "f1", "field_f1")
HEADLINE_MEAN_KEYS = (
    "overall_score_mean",
    "overall_extraction_score_mean",
    "accuracy_mean",
    "exact_match_mean",
)

# Registry task ids that must never source-chunk on pinned seed-42 draws
# (see ``specialist_llm.SINGLE_COVERAGE_CHUNK_CLASSES``).
SINGLE_COVERAGE_TASKS = frozenset({"correspondence", "insurance_claims"})

_SLUG_RE = re.compile(r"[^a-z0-9.]+")

# Slugified OpenRouter ids → the same filing keys used by decode profiles.
MODEL_FILE_ALIASES: dict[str, str] = {
    "qwen-qwen3-8b": "qwen3-8b",
    "qwen-qwen3.7-flash": "qwen3.7-flash",
    "deepseek-deepseek-v4.1-flash": "deepseek-v4.1-flash",
    "ibm-granite-granite-4.2-8b": "granite-4.2-8b",
}


def _prediction_meta(row: dict[str, Any]) -> dict[str, Any]:
    pred = row.get("prediction")
    return pred if isinstance(pred, dict) else {}


def _specialist_call_sanity_caveats(
    summary: dict[str, Any],
    case_rows: list[dict[str, Any]],
) -> list[str]:
    """Warn when call counts look like accidental chunking or runaway retries."""
    task = str(summary.get("task") or "")
    n_docs = len(case_rows) or int((summary.get("metrics") or {}).get("n") or 0)
    if n_docs <= 0:
        return []

    perf = summary.get("performance") or {}
    by_agent = perf.get("by_agent") if isinstance(perf.get("by_agent"), dict) else {}
    specialist_calls = sum(
        int(slot.get("calls") or 0)
        for slot in by_agent.values()
        if isinstance(slot, dict)
    )
    if specialist_calls <= 0:
        specialist_calls = sum(
            int(_prediction_meta(row).get("llm_calls") or 0) for row in case_rows
        )

    max_needed = max(
        (int(_prediction_meta(row).get("needed_chunks") or 1) for row in case_rows),
        default=1,
    )
    max_chunks = max(
        (int(_prediction_meta(row).get("chunks") or 1) for row in case_rows),
        default=1,
    )

    lines: list[str] = []
    if task in SINGLE_COVERAGE_TASKS and max_needed > 1:
        lines.append(
            f"- **Source-chunking bug:** up to `{max_needed}` coverage chunks on "
            f"`{task}` — pinned draws fit in one span; fix `_chunk_limit_for` "
            "before treating scores as comparable."
        )
    elif task == "merger_agreement" and max_chunks >= 8:
        lines.append(
            f"- **Merger chunking:** up to `{max_chunks}` source chunks per row — "
            "confirm the run model inherits merger-specific limits from "
            "`LARGE_COMPLETION_MODELS` / `CHUNK_CHARS`, not an accidental qwen3-8b default on Granite."
        )

    if task in SINGLE_COVERAGE_TASKS and specialist_calls > n_docs:
        lines.append(
            f"- **Call count:** `{specialist_calls}` specialist LLM calls for "
            f"`{n_docs}` documents — this is **not** source chunking when "
            f"`needed_chunks=1` (here max `{max_needed}`). Extra calls are "
            "JSON parse / network **retries** (`llm_call_budget=2`). "
            "Do not apply merger 48K chunk settings to correspondence or insurance."
        )
        if specialist_calls > n_docs * 15 // 10:
            lines.append(
                "- **High retry rate:** calls exceed ~1.5× document count — "
                "see runbook §4 (concurrency reliability) before accepting the wave as canonical."
            )
    return lines


def classify(subset: str | None) -> str:
    """Subset string -> report stem (``class:correspondence`` -> CORRESPONDENCE)."""
    if not subset:
        return "ALL"
    value = subset.strip().lower()
    if ":" in value:
        value = value.split(":", 1)[1]
    value = re.sub(r"[^a-z0-9]+", "_", value).strip("_")
    return value.upper() or "ALL"


def model_short(summary: dict[str, Any]) -> str:
    """Model filing key: decode-profile key when set, else slugified model id."""
    profile = (summary.get("params") or {}).get("decode_profile")
    if profile:
        return str(profile)
    model = str(summary.get("model") or "unknown")
    slug = _SLUG_RE.sub("-", model.lower()).strip("-")
    return MODEL_FILE_ALIASES.get(slug, slug)


def task_slug(summary: dict[str, Any]) -> str:
    """Task filing key: the eval task id (registry name), sanitized.

    Underscores are preserved (unlike ``model_short``'s dots-only slug) so
    ``insurance_claims`` files under ``insurance_claims/``, matching the
    task id used everywhere else (CLI ``--task``, experiment-log ``task``).
    """
    task = str(summary.get("task") or "unknown")
    return re.sub(r"[^a-z0-9_]+", "-", task.lower()).strip("-_") or "unknown"


def wave_size(summary: dict[str, Any]) -> int:
    """Draw size for the filename: sample when set, else n."""
    params = summary.get("params") or {}
    return int(params.get("sample") or params.get("n") or 0)


def _modal_contracts_v33(summary: dict[str, Any]) -> bool:
    """True when the contracts specialist ran the sandbox v33 prompt (Modal parity)."""
    if summary.get("prompt_version") == "contracts_specialist_v33":
        return True
    slot = (summary.get("prompt_versions") or {}).get("contracts_specialist") or {}
    return slot.get("key") == "contracts_specialist_v33"


def repo_relative_path(path: Path, base: Path | None = None) -> str:
    """Path under the repo root (for experiment-log links and JSONL fields)."""
    root = base or REPO_ROOT
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def run_report_path(summary: dict[str, Any], base_dir: Path | None = None) -> Path:
    """Immutable per-run write-up: ``<model>/<task>/runs/<run_id>.md``."""
    run_id = str(summary.get("run_id") or "unknown-run")
    base = base_dir or reports_dir()
    return base / model_short(summary) / task_slug(summary) / "runs" / f"{run_id}.md"


def report_path(summary: dict[str, Any], base_dir: Path | None = None) -> Path:
    """Deterministic report path for a run summary — always filed under
    ``<model>/<task>/`` so reports never pile up flat across specialists."""
    base = base_dir or reports_dir()
    short = model_short(summary)
    task = task_slug(summary)
    cls = classify((summary.get("dataset") or {}).get("subset"))
    v33 = "-V33" if cls == "CONTRACT" and _modal_contracts_v33(summary) else ""
    stem = f"RUN-{wave_size(summary)}-{cls}{v33}-{short.upper()}"
    return base / short / task / f"{stem}-REPORT.md"


def is_wave_run(summary: dict[str, Any], *, min_n: int = 20) -> bool:
    """True for substantive real eval waves that deserve a full write-up report."""
    if summary.get("mode") != "real" or summary.get("family") != "eval":
        return False
    params = summary.get("params") or {}
    wave = int(params.get("sample") or params.get("n") or (summary.get("metrics") or {}).get("n") or 0)
    return wave >= min_n


def run_cost_usd(summary: dict[str, Any]) -> float | None:
    """Best available run cost for cap checks: actual (case-derived) then roster est."""
    perf = summary.get("performance") or {}
    for key in ("cost_usd_total", "cost_usd_est_total"):
        value = perf.get(key)
        if isinstance(value, (int, float)):
            return float(value)
    return None


def cap_status(summary: dict[str, Any], profile: dict[str, Any]) -> dict[str, Any] | None:
    """Compare the run's cost against the profile's cap."""
    cap = profile.get("cost_cap_usd")
    if cap is None:
        return None
    cost = run_cost_usd(summary)
    over = isinstance(cost, (int, float)) and cost > cap
    return {
        "cap_usd": cap,
        "cost_usd_est": cost,
        "cost_usd_total": cost,
        "status": "over_cap" if over else "under_cap",
    }


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.4f}" if abs(value) < 1000 else f"{value:.1f}"
    return str(value)


def _pick(scores: dict[str, Any], keys: tuple[str, ...]) -> Any:
    for key in keys:
        value = scores.get(key)
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return value
    return None


def render_report(summary: dict[str, Any], case_rows: list[dict[str, Any]]) -> str:
    """Render the Markdown report body for one comparison run."""
    params = summary.get("params") or {}
    dataset = summary.get("dataset") or {}
    performance = summary.get("performance") or {}
    metrics = summary.get("metrics") or {}
    applied = params.get("decode_budget_applied") or {}
    sampling = params.get("decode_sampling")
    by_agent = performance.get("by_agent") or {}

    latencies = sorted(
        float(r["latency_ms"]) / 1000.0
        for r in case_rows
        if isinstance(r.get("latency_ms"), (int, float))
    )
    p50 = latencies[len(latencies) // 2] if latencies else None
    p95_raw = performance.get("latency_ms_p95")
    p95 = p95_raw / 1000.0 if isinstance(p95_raw, (int, float)) else None
    latency_max = latencies[-1] if latencies else None

    tok_in = performance.get("tokens_prompt_total")
    tok_out = performance.get("tokens_completion_total")
    cost_actual = performance.get("cost_usd_total")
    cost_est = performance.get("cost_usd_est_total")
    cost_expected = performance.get("expected_cost_usd")
    n_scored = len(case_rows)
    n_ok = sum(
        1
        for r in case_rows
        if not r.get("error")
        and not ((r.get("prediction") or {}).get("_parse_error") if isinstance(r.get("prediction"), dict) else False)
    )
    cost_per_doc_actual = (
        (cost_actual / n_scored) if isinstance(cost_actual, (int, float)) and n_scored else None
    )
    cost_per_doc_est = (cost_est / n_scored) if isinstance(cost_est, (int, float)) and n_scored else None

    wall = summary.get("duration_s")
    # Serial-vs-batched proof (same arithmetic the Modal reports print).
    serial_sum = sum(latencies) if latencies else None

    cap = summary.get("cost_cap") or {}
    headline = next((metrics[k] for k in HEADLINE_MEAN_KEYS if k in metrics), None)

    lines: list[str] = []
    lines.append(f"# Run report — `{summary.get('run_id')}` (API leg)")
    lines.append("")
    lines.append("Comparison report for the OpenRouter API leg, metric-for-metric against")
    lines.append("the Modal/vLLM leg reports (same wave+class stem = paired report).")
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(f"| run_id | `{summary.get('run_id')}` |")
    lines.append(f"| task / agent | `{summary.get('task')}` |")
    lines.append(f"| prompt | `{_fmt(summary.get('prompt_version'))}` ({_fmt(summary.get('prompt_source'))}) |")
    lines.append(f"| engine | `{_fmt(summary.get('model'))}` (OpenRouter API) |")
    lines.append(f"| profile / provider | `{_fmt(params.get('decode_profile'))}` / `openrouter` |")
    lines.append(f"| dataset | {_fmt(dataset.get('repo'))} rev `{_fmt(dataset.get('revision'))}` |")
    lines.append(
        f"| subset / draw | `{_fmt(dataset.get('subset'))}` — {wave_size(summary) or n_scored} docs, "
        f"seed {params.get('seed')} |"
    )
    lines.append(f"| timestamp | `{_fmt(summary.get('started_at'))}` |")
    lines.append(f"| pipeline git | `{_fmt(summary.get('pipeline_git'))}` |")
    lines.append(f"| subset manifest | `{_fmt(dataset.get('subset_manifest_path'))}` |")
    lines.append(f"| eval git | `{_fmt((summary.get('git') or {}).get('commit'))}` |")
    lines.append(f"| finished | `{_fmt(summary.get('finished_at'))}` |")
    lines.append("")

    lines.append("## Run configuration")
    lines.append("")
    lines.append("| control | value |")
    lines.append("|---|---|")
    config_rows = [
        ("family / invoke", f"{summary.get('family')} / {summary.get('invoke')}"),
        ("mode", summary.get("mode")),
        ("concurrency", params.get("concurrency")),
        ("seed", params.get("seed")),
        ("sample / n", f"{params.get('sample')} / {params.get('n')}"),
        ("scorer", params.get("scorer")),
        ("decode profile", params.get("decode_profile")),
        ("prompt source / lineage", f"{summary.get('prompt_source')} / {summary.get('prompt_lineage')}"),
        ("trace backend", summary.get("trace_backend")),
        ("resumed_from", params.get("resumed_from")),
        ("dry_run", params.get("dry_run")),
    ]
    for label, value in config_rows:
        lines.append(f"| {label} | {_fmt(value)} |")
    trace_ids = summary.get("trace_ids")
    if trace_ids:
        lines.append(f"| trace ids | `{_fmt(trace_ids)}` |")
    lines.append("")

    lines.append("## Runtime performance")
    lines.append("")
    lines.append("| metric | value |")
    lines.append("|---|---|")
    lines.append(f"| started_at | `{_fmt(summary.get('started_at'))}` |")
    lines.append(f"| finished_at | `{_fmt(summary.get('finished_at'))}` |")
    lines.append(f"| duration_s (wall) | {_fmt(wall)} |")
    lines.append(f"| latency_ms_mean | {_fmt(performance.get('latency_ms_mean'))} |")
    lines.append(f"| latency_ms_p95 | {_fmt(performance.get('latency_ms_p95'))} |")
    lines.append("")

    lines.append("## Headline results")
    lines.append("")
    lines.append("| metric | value |")
    lines.append("|---|---|")
    lines.append(
        f"| docs ok / total | **{n_ok} / {n_scored}** (`errors={metrics.get('errors', 0)}`) |"
    )
    if headline is not None:
        lines.append(f"| **{HEADLINE_MEAN_KEYS[0]}** | **{_fmt(headline)}** |")
    for key in sorted(metrics):
        if key == "n" or key in HEADLINE_MEAN_KEYS:
            continue
        value = metrics[key]
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            lines.append(f"| {key} | {round(value, 5)} |")
    lines.append(f"| thinking_recovered (stripped + re-scored) | {params.get('thinking_recovered', 0)} |")
    stats = rra.headline_score_stats(case_rows)
    if stats.get("mean") is not None:
        lines.append(
            f"| overall (per-doc) | **{stats['mean']:.4f}** "
            f"(sd {stats['sd']:.4f}, min {stats['min']:.4f}, max {stats['max']:.4f}) |"
        )
    lines.append("")

    lines.append("## Serving / cost metrics (API leg)")
    lines.append("")
    lines.append("| metric | value |")
    lines.append("|---|---|")
    lines.append(f"| wall (run duration) | {_fmt(wall)} s |")
    lines.append(f"| concurrency | {_fmt(params.get('concurrency'))} |")
    lines.append("| cold boot | N/A (serverless API — no cold boot) |")
    lines.append("| gpu_seconds | N/A (no local GPU) |")
    lines.append(f"| cost expected (wave planning) | **{_fmt(cost_expected)}** USD |")
    lines.append(f"| cost actual (derived from case rows) | **{_fmt(cost_actual)}** USD |")
    lines.append(f"| cost estimated (roster token rates) | **{_fmt(cost_est)}** USD |")
    lines.append(f"| cost per document (actual) | {_fmt(cost_per_doc_actual)} USD |")
    lines.append(f"| cost per document (estimated) | {_fmt(cost_per_doc_est)} USD |")
    lines.append(
        f"| latency e2e / p50 / p95 / max | {_fmt(wall)} / {_fmt(p50)} / {_fmt(p95)} / {_fmt(latency_max)} s |"
    )
    lines.append(
        f"| prompt / completion / total tokens | {_fmt(tok_in)} / {_fmt(tok_out)} / "
        f"{_fmt((tok_in or 0) + (tok_out or 0))} |"
    )
    lines.append(f"| cost cap | {_fmt(cap.get('cap_usd'))} USD (profile) -> **{_fmt(cap.get('status'))}** |")
    lines.append("")
    if serial_sum is not None and isinstance(wall, (int, float)) and wall:
        lines.append(
            f"**Serial-vs-batched proof:** sum(per-doc latency) = {serial_sum:.1f} s vs wall = {wall:.1f} s "
            f"-> wall/serial factor {serial_sum / wall:.2f}x at concurrency {params.get('concurrency', 1)}."
        )
        lines.append("")

    lines.append("## Decode posture")
    lines.append("")
    lines.append("| control | value |")
    lines.append("|---|---|")
    lines.append(f"| sampling override | `{json.dumps(sampling) if sampling else 'none (pipeline posture)'}` |")
    lines.append(f"| sampling injected on wire | {applied.get('sampling_injected', False)} |")
    lines.append(f"| per-agent completion budgets | `{json.dumps(applied.get('max_tokens_by_agent') or {}, sort_keys=True)}` |")
    lines.append(f"| per-call timeout | {params.get('decode_call_timeout_s') or 'pipeline default'} s |")
    lines.append("")

    if by_agent:
        lines.append("## Per-agent usage")
        lines.append("")
        lines.append("| agent | calls | prompt tok | completion tok | total tok | cost est | models |")
        lines.append("|---|---|---|---|---|---|---|")
        for agent, usage in sorted(by_agent.items()):
            models = ", ".join(usage.get("models") or []) or "—"
            lines.append(
                f"| `{agent}` | {_fmt(usage.get('calls'))} | {_fmt(usage.get('prompt_tokens'))} | "
                f"{_fmt(usage.get('completion_tokens'))} | {_fmt(usage.get('total_tokens'))} | "
                f"{_fmt(usage.get('cost_usd_est'))} | {models} |"
            )
        lines.append("")

    lines.extend(
        rra.render_analyst_insights(summary, case_rows, wall=wall, p50=p50, p95=p95)
    )
    lines.extend(rra.render_scoring_method(summary, case_rows))
    lines.extend(rra.render_figures_note())
    lines.extend(rra.render_strata(case_rows))

    lines.append("## Per-document scores")
    lines.append("")
    lines.append("| # | doc id | subclass | overall | f1 | latency s | tok in | tok out | error |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for i, row in enumerate(case_rows, 1):
        scores = row.get("scores") or {}
        prediction = row.get("prediction") or {}
        error = row.get("error") or (
            "parse_error"
            if isinstance(prediction, dict) and prediction.get("_parse_error")
            else None
        )
        tokens = row.get("tokens") if isinstance(row.get("tokens"), dict) else {}
        latency = row.get("latency_ms")
        latency = latency / 1000.0 if isinstance(latency, (int, float)) else None
        doc_id = row.get("case_id") or row.get("filename")
        lines.append(
            f"| {i} | `{_fmt(doc_id)}` | {_fmt(row.get('expected_subclass'))} | "
            f"{_fmt(_pick(scores, OVERALL_KEYS))} | {_fmt(_pick(scores, F1_KEYS))} | {_fmt(latency)} | "
            f"{_fmt(tokens.get('prompt'))} | {_fmt(tokens.get('completion'))} | {_fmt(error)} |"
        )
    scored = [
        float(v)
        for v in (_pick(r.get("scores") or {}, OVERALL_KEYS) for r in case_rows)
        if isinstance(v, (int, float))
    ]
    if scored:
        lines.append("")
        lines.append(
            f"- scored rows: {len(scored)}/{n_scored}; "
            f"min={min(scored):.4f} max={max(scored):.4f} mean={sum(scored) / len(scored):.4f}"
        )
    lines.append("")

    lines.extend(rra.render_reproduce(summary))
    lines.extend(rra.render_artifacts(summary))

    lines.append("## Caveats / notes")
    lines.append("")
    lines.append(f"- mode: **{summary.get('mode')}**; trace backend: `{_fmt(summary.get('trace_backend'))}`")
    lines.append(f"- decode profile: `{_fmt(params.get('decode_profile'))}`; budgets/timeout per issue #18 §3")
    if params.get("thinking_recovered"):
        lines.append(
            f"- {params.get('thinking_recovered')} prediction(s) recovered post-hoc by stripping "
            "thinking envelopes (issue #18 §4) — headline scores reflect the *recovered* parse"
        )
    if params.get("resumed_from"):
        lines.append(f"- resumed run: `{_fmt(params.get('resumed_from'))}` (subset manifest preserved)")
    for note in _specialist_call_sanity_caveats(summary, case_rows):
        lines.append(note)
    lines.append(
        "- Pair with the Modal leg: same `RUN-<wave>-<CLASS>` stem in "
        "`local-mailroom-sandbox/reports/` (e.g. `RUN-20-CORRESPONDENCE-AWQ-REPORT.md`)."
    )
    lines.append("")
    return "\n".join(lines)


def resolve_report_path(summary: dict[str, Any], base_dir: Path | None = None) -> Path | None:
    """Best on-disk write-up for a run (per-run file, else canonical wave stem)."""
    run_path = run_report_path(summary, base_dir)
    if run_path.is_file():
        return run_path
    wave_path = report_path(summary, base_dir)
    return wave_path if wave_path.is_file() else None


